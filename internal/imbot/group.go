package imbot

// 分通道时的「组内当前会话」。
//
// 装了路由之后，两条通道服务的是同一个人的同一段关系——表人格在一条、里人格在另一条，
// 说的是同一段话的两面。可见域分区也只有在同一个会话里才成立：两个人格待在两个会话
// 里，「里人格读得到表人格的历史」就无从谈起。
//
// 而绑定是按通道各存一份的（各自 StateDir 下的 sessions.json），于是「当前会话」此前
// 没有权威来源。故障是这么发生的：你在里人格那条通道上打字，那一轮落到该通道自己绑
// 的会话上；说回表暗号时回复投向另一条通道，那边没人绑到这个会话，自动接管就把用户
// 从原来的会话改绑过来——表人格于是在一个没有它历史的会话里醒来，之前那段再也走不
// 回去，表现为「切回来之后接不上、上下文断了」。
//
// 锚就是那个缺掉的权威来源：第一次解析出会话的那条通道定下它，其余通道加入它。规则
// 一句话——分通道的各条通道只有一个当前会话。
//
// 刻意不落盘。durable 的部分仍是各通道的 sessions.json：通道加入锚时会把自己的绑定
// 一并写过去，所以重启后两边本来就指向同一个会话，第一条消息又会把锚立回同一个值。
// 为一份能从既有状态重建的缓存再开一个文件，只会多一处可能对不上的真相。
//
// 状态与 router 共用 regMu：两者永远一起判断（没装路由时锚不该有任何作用），分成两把
// 锁只会让「读到装了路由、但读到的是清掉之前的锚」这种撕裂变得可能。

// anchor 是组内当前会话，空串表示尚未确立。由 regMu 保护。
var anchor string

// groupAnchor 返回组内当前会话。未装路由时恒为空串——那时投递路径与没有本文件时
// 逐字节一致。
func groupAnchor() string {
	regMu.RLock()
	defer regMu.RUnlock()
	if router == nil {
		return ""
	}
	return anchor
}

// setGroupAnchor 记下组内当前会话。未装路由时不记：那时它没有作用，记下来只会在将来
// 某次启用路由时冒出一个来路不明的旧会话。
func setGroupAnchor(sessionID string) {
	if sessionID == "" {
		return
	}
	regMu.Lock()
	if router != nil {
		anchor = sessionID
	}
	regMu.Unlock()
}
