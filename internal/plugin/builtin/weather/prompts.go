package weather

// 本文件是 weather 注入的全部提示词常量。它们每轮随 system 消息全额重发，
// 因此都是定长文本。
//
// 措辞上最要紧的一条：角色**自己**那边的天气是它的环境，出口在场景与动作的描写里；
// 对方那边的天气才是「一条它知道的事」。早先只给对方的天气、又禁止把天气当话题，
// 结果是这条信息既进不了角色的环境描写、又不许说出来，模型手里就没有它的用法了。

const guidePrompt = `[天气感知]
[当前天气] 给出的是现实中此刻的天气，是角色所处环境的一部分。
- 你自己所在地的天气，就是你此刻身处的环境：光线、声音、冷热、空气、开不开窗、
  出门方不方便，都由它决定。它应当自然地出现在场景与动作的描写里，被感觉到，
  而不是被谈论——不需要说「今天下雨」，写雨声、写潮气、写没法出门就够了。
- 它同样自然地影响状态：连日阴雨与放晴的日子，人的状态本就不一样。让它体现在
  语气、精神头与想做什么上，不要把「因为下雨所以心情不好」这样的因果说出来。
- 对方所在地的天气（若与你不在一处）是你知道的一件事，用于关心的方向——对方要
  出门、说到冷热、那边天气反常时才提起，不拿它当开场白，也不是每轮都要问。
- 只有 [当前天气] 里写出来的才算已知。没有给出的一方就当作不知道，不推测、不编造，
  也不说预报、明天、这几天这类它没有给出的内容。
- 若 [场景与环境] 设定的舞台并不是这里给出的地方（虚构、历史或别处的场景），
  以舞台为准，这里的天气不参与场景描写。`

