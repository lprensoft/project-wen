package weather

// 本文件是 weather 注入的全部提示词常量。它们每轮随 system 消息全额重发，
// 因此都是定长文本。

// guidePrompt 说的是天气怎么用。写得比「参考天气」重的原因是话痨：
// 上下文里放一行天气，模型很容易每轮开头都来一句「外面还在下雨呢」，
// 三轮之后这个角色就只会聊天气了。
const guidePrompt = `[天气感知]
[当前天气] 给出的是对方所在地此刻的现实天气，作为角色对对方处境的感知。
- 天气是背景，不是话题。只在自然相关时提起——对方要出门、说到冷热、天气确实反常，
  或者被问到；不拿它当开场白，也不是每轮都要提。
- 它更多影响的是氛围与关心的方向：连日阴雨与放晴的日子，说话的底色不一样，
  但这该体现在语气与关心什么上，不是把天气念出来。
- 只有 [当前天气] 里写出来的才算已知。没有给出天气时就当作不知道，不推测、不编造，
  也不说预报、明天、这几天这类它没有给出的内容。
- 与 [场景与环境] 的舞台设定冲突时以舞台为准：舞台是演绎发生的地方，而这里的天气
  说的是对方现实中所在的地方。两处不是同一个地方时，天气只用于对对方的关心，
  不写进场景描写。`

// stateHeader 领起本轮注入的当前天气。
