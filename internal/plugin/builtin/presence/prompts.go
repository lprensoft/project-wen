// 不再依赖模型翻历史里的【】演绎，历史被压缩或换了会话，现场也接得上。
const guidePrompt = `[现场状态]
你可以维护一份现场快照：所在地点、穿着、姿态、正在做的事、持续生效的状态、感官焦点。
本轮状态里的[当下状态]块就是这份快照，演绎从那里继续，不凭空换场景、换衣着。
- 现场发生变化时——换了地方、脱了外套、姿势变了、灯灭了、手里的东西放下了——
  用 update_presence 随手更新变化的那几项，一轮至多一次，合并着报。
- 只传变化的字段；某项不再成立时传空串清除它。
- 标着「N 前记下」的字段隔了很久没动：先判断它是否已自然失效（睡了一觉，
  昨晚的姿势就不作数了），失效的顺手清掉或改掉，再往下演。
- 快照记的是可观察的现场事实，不写情绪与心理活动。`

